(function () {
  const SUPPORTED = Object.keys(window.I18N);
  const KEY = 'hf-lang';

  function initial() {
    const fromUrl = new URLSearchParams(location.search).get('lang');
    if (SUPPORTED.includes(fromUrl)) return fromUrl;
    try {
      const saved = localStorage.getItem(KEY);
      if (SUPPORTED.includes(saved)) return saved;
    } catch {}
    return (navigator.language || '').toLowerCase().startsWith('vi') ? 'vi' : 'en';
  }

  const listeners = [];
  const i18n = {
    supported: SUPPORTED,
    lang: initial(),
    // t('card.to', { to: 'Mom' }, 'vi'): falls back to English, then to the key itself
    t(key, vars, lang) {
      const l = SUPPORTED.includes(lang) ? lang : this.lang;
      let s = window.I18N[l][key] ?? window.I18N.en[key] ?? key;
      if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
      return s;
    },
    set(lang) {
      if (!SUPPORTED.includes(lang) || lang === this.lang) return;
      this.lang = lang;
      try { localStorage.setItem(KEY, lang); } catch {}
      this.apply();
      listeners.forEach(fn => fn(lang));
    },
    onChange(fn) { listeners.push(fn); },
    // Fill elements marked with data-i18n (text), data-i18n-placeholder, data-i18n-aria
    apply(root = document) {
      document.documentElement.lang = this.lang;
      root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = this.t(el.dataset.i18n); });
      root.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.placeholder = this.t(el.dataset.i18nPlaceholder); });
      root.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', this.t(el.dataset.i18nAria)); });
      const title = document.querySelector('title[data-i18n-title]');
      if (title) document.title = this.t(title.dataset.i18nTitle);
      root.querySelectorAll('.lang-toggle').forEach(btn => {
        btn.textContent = this.t('lang.switch');
        btn.lang = this.lang === 'vi' ? 'en' : 'vi';
      });
    },
  };
  window.i18n = i18n;

  document.addEventListener('click', e => {
    if (e.target.closest('.lang-toggle')) i18n.set(i18n.lang === 'vi' ? 'en' : 'vi');
  });
  document.addEventListener('DOMContentLoaded', () => i18n.apply());
})();
